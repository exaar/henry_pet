/// One embedded sprite set (tray "Skin"). The list is generated by build.rs.
pub struct Skin {
    pub id: &'static str,
    pub label: &'static str,
    pub sprite: &'static [u8],
    pub manifest: Option<&'static str>,
}

// SKINS: &[Skin] (generated by build.rs; Henry's own first)
include!(concat!(env!("OUT_DIR"), "/sprite.rs"));

/// The skin with this id, else the first one (an unknown id in settings.json never breaks startup).
pub fn skin(id: &str) -> &'static Skin {
    SKINS.iter().find(|s| s.id == id).unwrap_or(&SKINS[0])
}

const CODEX: [&str; 9] = ["idle", "running-right", "running-left", "waving", "jumping", "failed", "waiting", "running", "review"];
const LEGACY: [&str; 8] = ["idle", "wave", "run", "failed", "review", "jump", "extra1", "extra2"];
pub const LOOP_MS: u32 = 1100;

/// Logical animation -> groups to try, in order. A group matches `name`, `name_*` and `name-*`
/// (variants like `sleep_curl`, `idle-2`, `walk_left`).
// "idle" is always sitting (2026-11-11); `stand` is only the in-between pose (sit <-> walk)
// and what air / held / landing fall back to.
pub fn chain(want: &str) -> &'static [&'static str] {
    match want {
        "idle" => &["idle", "sit"],
        "rest" => &["sit", "idle"],
        "walk" => &["walk"],
        "trot" => &["trot", "walk"],
        "look" => &["look", "idle"],
        "stare" => &["stare", "sit", "idle"],
        "petted" => &["petted", "stare", "sit", "idle"],
        "wave" => &["wave", "stare", "idle"],
        "sleep" => &["sleep", "idle"],
        "twitch" => &["twitch", "sleep", "idle"],
        "groom" => &["groom", "idle"],
        "stretch" => &["stretch", "idle"],
        "jump" => &["jump", "held", "fly", "stand"],
        "fly" => &["fly", "jump", "stand", "idle"],
        "fall" => &["fall", "fly", "jump", "stand", "idle"],
        "land" => &["land", "stand", "idle"],
        "held" => &["held", "fly", "jump", "stand", "idle"],
        "splat" => &["splat", "idle"],
        "failed" => &["failed", "splat", "idle"],
        "hop" => &["hop", "jump", "wave", "idle"],
        "push" => &["push", "walk"],
        "climb" => &["climb", "walk"],
        _ => &["idle"],
    }
}

pub fn in_group(name: &str, group: &str) -> bool {
    name == group || name.strip_prefix(group).is_some_and(|r| r.starts_with('_') || r.starts_with('-'))
}

#[derive(Deserialize)]
#[serde(untagged)]
enum Frames {
    Count(u32),
    List(Vec<u32>),
}

#[derive(Deserialize)]
struct AnimDef {
    row: u32,
    #[serde(default)]
    frames: Option<Frames>,
    #[serde(default)]
    ms: Option<u32>,
    #[serde(default, rename = "loop")]
    looped: Option<bool>,
    #[serde(default)]
    facing: Option<String>,
    /// Body pose: "stand" (default), "sit", "lie". Stand<->sit plays trans_sit / trans_stand between.
    #[serde(default)]
    pose: Option<String>,
    /// Grab point in cell px (held: the scruff); the engine hangs a soft body chain from it (slinky.rs).
    #[serde(default)]
    pivot: Option<[f64; 2]>,
    /// Walk: per frame, sprite px the planted paw slides back while it shows (one value per played frame).
    #[serde(default)]
    steps: Option<Vec<f64>>,
    /// Per played frame: sprite px forward when it appears; one extra value = on leaving (trans_walk).
    #[serde(default)]
    travel: Option<Vec<f64>>,
}

#[derive(Deserialize)]
struct Manifest {
    cell: [u32; 2],
    /// Default facing of the art: "right" (default), "left" or "none".
    #[serde(default)]
    facing: Option<String>,
    /// "auto" (nearest when enlarging, smooth when shrinking), "nearest" or "smooth".
    #[serde(default)]
    filter: Option<String>,
    /// Paw line in cell pixels (first transparent row under the feet). Default: measured on idle.
    #[serde(default)]
    foot: Option<u32>,
    animations: BTreeMap<String, AnimDef>,
}

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Filter {
    Auto,
    Nearest,
    Smooth,
}

pub struct Anim {
    pub name: String,
    pub row: u32,
    pub seq: Vec<u32>,
    pub ms: u32,
    pub once: bool,
    /// +1 drawn facing right, -1 left, 0 no direction (never mirrored).
    pub facing: i8,
    pub pose: Pose,
    /// Grab point in cell px, if the art has one (held).
    pub pivot: Option<(f64, f64)>,
    /// Walk: sprite px each frame carries her (how far the planted paw slides back while it shows).
    /// The brain picks the frame from the distance covered and pins the drawing to the paw: no foot slip.
    pub steps: Vec<f64>,
    /// Sprite px she moves forward as each played frame appears, plus one more when it ends (trans_walk).
    pub travel: Vec<f64>,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Pose {
    Stand,
    Sit,
    Lie,
}

pub struct Sheet {
    w: u32,
    px: Vec<u8>, // RGBA, straight alpha
    pub cell_w: u32,
    pub cell_h: u32,
    pub anims: Vec<Anim>,
    pub filter: Filter,
    /// "henry" (own manifest) or "placeholder" (petdex layout mapped by code).
    pub kind: &'static str,
    /// Skin id this sheet came from.
    pub skin: &'static str,
    pub info: SpriteInfo,
}

fn facing_of(s: Option<&str>, default: i8) -> i8 {
    match s {
        Some("right") => 1,
        Some("left") => -1,
        Some("none") => 0,
        _ => default,
    }
}

impl Sheet {
    pub fn load(skin_id: &str) -> Sheet {
        let skin = skin(skin_id);
        let img = image::load_from_memory(skin.sprite).expect("embedded spritesheet decodes").to_rgba8();
        let (w, h) = img.dimensions();
        let px = img.into_raw();
        let alpha = |x: u32, y: u32| px[((y * w + x) * 4 + 3) as usize];
        let manifest = skin.manifest.filter(|t| t.contains("\"animations\"")).map(|t| match serde_json::from_str::<Manifest>(t) {
            Ok(m) => m,
            Err(e) => panic!("pet.json next to the spritesheet is invalid: {e}"),
        });
        let filled = |c: u32, r: u32, cw: u32, ch: u32| {
            (0..ch).step_by(2).any(|y| (0..cw).step_by(2).any(|x| alpha(c * cw + x, r * ch + y) > 16))
        };
        let count = |r: u32, cw: u32, ch: u32, cols: u32| (0..cols).filter(|&c| filled(c, r, cw, ch)).map(|c| c + 1).max().unwrap_or(0);

        let (cw, ch, mut anims, filter, foot, kind) = if let Some(m) = manifest {
            let [cw, ch] = m.cell;
            assert!(cw > 0 && ch > 0 && w >= cw && h >= ch, "pet.json cell {cw}x{ch} does not fit the {w}x{h} sheet");
            let (cols, nrows) = (w / cw, h / ch);
            let base = facing_of(m.facing.as_deref(), 1);
            let anims: Vec<Anim> = m
                .animations
                .into_iter()
                .filter(|(_, d)| d.row < nrows)
                .map(|(name, d)| {
                    let seq: Vec<u32> = match d.frames {
                        Some(Frames::List(v)) => v.into_iter().filter(|f| *f < cols).collect(),
                        Some(Frames::Count(n)) if n > 0 => (0..n.min(cols)).collect(),
                        _ => (0..count(d.row, cw, ch, cols)).collect(),
                    };
                    let facing = facing_of(d.facing.as_deref(), base);
                    let pose = match d.pose.as_deref() {
                        Some("sit") => Pose::Sit,
                        Some("lie") => Pose::Lie,
                        _ => Pose::Stand,
                    };
                    Anim { name, row: d.row, seq, ms: d.ms.unwrap_or(LOOP_MS), once: d.looped == Some(false), facing, pose, pivot: d.pivot.map(|[x, y]| (x, y)), steps: d.steps.filter(|v| v.iter().all(|s| *s > 0.0)).unwrap_or_default(), travel: d.travel.unwrap_or_default() }
                })
                .filter(|a| !a.seq.is_empty())
                .collect();
            let filter = match m.filter.as_deref() {
                Some("nearest") => Filter::Nearest,
                Some("smooth") => Filter::Smooth,
                _ => Filter::Auto,
            };
            (cw, ch, anims, filter, m.foot, "henry")
        } else {
            // petdex placeholder: rows by fixed order, mapped onto Henry's animation names
            let legacy = w == 1728 && h == 1664;
            let cols = if legacy { 9 } else { (w as f64 / 192.0).round() as u32 };
            let nrows = if legacy { 8 } else { (h as f64 / 208.0).round() as u32 };
            let (cw, ch) = (w / cols, h / nrows);
            let names: Vec<&str> = (0..nrows as usize).map(|r| if legacy { LEGACY.get(r) } else { CODEX.get(r) }.copied().unwrap_or("")).collect();
            let row = |n: &str| names.iter().position(|x| *x == n).map(|r| r as u32);
            let mut anims = Vec::new();
            let mut add = |name: &str, src: &str, frames: Option<Vec<u32>>, ms: u32, facing: i8| {
                if let Some(r) = row(src) {
                    let seq = frames.unwrap_or_else(|| (0..count(r, cw, ch, cols)).collect());
                    if !seq.is_empty() {
                        anims.push(Anim { name: name.into(), row: r, seq, ms, once: false, facing, pose: Pose::Stand, pivot: None, steps: Vec::new(), travel: Vec::new() });
                    }
                }
            };
            add("idle", "idle", None, LOOP_MS, 0);
            if legacy {
                add("walk", "run", None, LOOP_MS, 0);
                add("wave", "wave", None, LOOP_MS, 0);
                add("hop", "jump", None, LOOP_MS, 0);
            } else {
                add("walk", "running-right", None, LOOP_MS, 1);
                add("walk_left", "running-left", None, LOOP_MS, -1);
                add("wave", "waving", None, LOOP_MS, 0);
                add("stare", "waiting", None, LOOP_MS, 0);
                add("hop", "jumping", None, LOOP_MS, 0);
                add("held", "jumping", Some(vec![1]), LOOP_MS, 0);
                add("fly", "jumping", Some(vec![2]), LOOP_MS, 0);
                add("fall", "jumping", Some(vec![3]), LOOP_MS, 0);
            }
            add("look", "review", None, LOOP_MS, 0);
            add("splat", "failed", None, 1600, 0);
            // lying with eyes closed / its twitch (PLAN #24)
            add("sleep", "failed", Some(vec![3]), LOOP_MS, 0);
            add("twitch", "failed", Some(vec![2]), LOOP_MS, 0);
            (cw, ch, anims, Filter::Auto, None, "placeholder")
        };
        if anims.is_empty() {
            panic!("spritesheet has no usable animations");
        }
        // idle first so that index 0 is a sane last resort
        anims.sort_by_key(|a| !in_group(&a.name, "idle"));
        let foot = foot.unwrap_or_else(|| {
            let a = &anims[0];
            a.seq
                .iter()
                .filter_map(|&c| (0..ch).rev().find(|y| (0..cw).any(|x| alpha(c * cw + x, a.row * ch + y) > 16)))
                .map(|y| y + 1)
                .max()
                .unwrap_or(ch)
        });
        let info = SpriteInfo { cell_w: cw as f64, cell_h: ch as f64, foot_y: foot as f64 };
        Sheet { w, px, cell_w: cw, cell_h: ch, anims, filter, kind, skin: skin.id, info }
    }

    /// Opaque at cell px (x, y) of animation `a`, sheet frame (column) `f`.
    pub fn opaque_at(&self, a: usize, f: u32, x: i32, y: i32) -> bool {
        let (cw, ch) = (self.cell_w as i32, self.cell_h as i32);
        if x < 0 || y < 0 || x >= cw || y >= ch {
            return false;
        }
        let an = &self.anims[a];
        self.px[((((an.row as i32 * ch + y) * self.w as i32) + f as i32 * cw + x) * 4 + 3) as usize] > 16
    }

    /// Index of the animation named exactly `name`.
    pub fn find(&self, name: &str) -> Option<usize> {
        self.anims.iter().position(|a| a.name == name)
    }

    pub fn has(&self, group: &str) -> bool {
        self.anims.iter().any(|a| in_group(&a.name, group))
    }

    /// Duration of the animation `want` resolves to first, if it plays once (else None).
    pub fn once_ms(&self, want: &str) -> Option<u32> {
        let g = chain(want).iter().find(|g| self.has(g))?;
        self.anims.iter().find(|a| in_group(&a.name, g)).filter(|a| a.once).map(|a| a.ms)
    }

    /// Last opaque row + 1 (cell px) over all frames of `a`: where the held chain ends.
    pub fn art_bottom(&self, a: &Anim) -> f64 {
        let (cw, ch) = (self.cell_w, self.cell_h);
        a.seq
            .iter()
            .filter_map(|&c| (0..ch).rev().find(|&y| (0..cw).any(|x| self.px[(((a.row * ch + y) * self.w + c * cw + x) * 4 + 3) as usize] > 16)))
            .map(|y| y as f64 + 1.0)
            .fold(0.0, f64::max)
    }

    /// A cell scaled to w x h, premultiplied BGRA, ready to blit.
    pub(crate) fn scaled_cell(&self, row: u32, frame: u32, w: u32, h: u32) -> Vec<u8> {
        let (cw, ch) = (self.cell_w, self.cell_h);
        let mut cell = image::RgbaImage::new(cw, ch);
        for y in 0..ch {
            for x in 0..cw {
                let s = (((row * ch + y) * self.w + frame * cw + x) * 4) as usize;
                let a = self.px[s + 3] as u32;
                let pm = |c: u8| (c as u32 * a / 255) as u8;
                cell.put_pixel(x, y, image::Rgba([pm(self.px[s]), pm(self.px[s + 1]), pm(self.px[s + 2]), a as u8]));
            }
        }
        let shrink = w < cw || h < ch;
        let f = match self.filter {
            Filter::Nearest => image::imageops::FilterType::Nearest,
            Filter::Smooth => image::imageops::FilterType::Triangle,
            Filter::Auto if shrink => image::imageops::FilterType::Triangle,
            Filter::Auto => image::imageops::FilterType::Nearest,
        };
        let out = if (w, h) == (cw, ch) { cell } else { image::imageops::resize(&cell, w, h, f) };
        let mut raw = out.into_raw();
        for p in raw.chunks_exact_mut(4) {
            p.swap(0, 2); // RGBA -> BGRA
        }
        raw
    }
}

/// Chosen animation for this frame.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct Pick {
    pub anim: usize,
    pub mirror: bool,
    /// Resolved to a stand-in group, not the one asked for first.
    pub fallback: bool,
}

/// Fallback + variant choice. A variant sticks until the brain bumps `epoch` (a new act), so a sleeping
/// Henry stays in the same pose through twitches.
pub struct Picker {
    epoch: u64,
    chosen: HashMap<(&'static str, i8), usize>,
}

impl Picker {
    pub fn new() -> Self {
        Self { epoch: 0, chosen: HashMap::new() }
    }

    /// `pose`: her current body pose. A stand-in (fallback group) keeps that pose if the group has a
    /// variant in it, so e.g. "look" falling back to idle doesn't make her sit down / get up for nothing.
    pub fn pick(&mut self, sheet: &Sheet, want: &str, dir: i8, epoch: u64, pose: Pose, rng: &mut impl Rng) -> Pick {
        if epoch != self.epoch {
            self.epoch = epoch;
            self.chosen.clear();
        }
        let dir = if dir < 0 { -1 } else { 1 };
        for (i, g) in chain(want).iter().enumerate() {
            let members: Vec<usize> = (0..sheet.anims.len()).filter(|&m| in_group(&sheet.anims[m].name, g)).collect();
            if members.is_empty() {
                continue;
            }
            let fit: Vec<usize> = members.iter().copied().filter(|&m| sheet.anims[m].facing == 0 || sheet.anims[m].facing == dir).collect();
            let mut pool = if fit.is_empty() { members } else { fit };
            if i > 0 {
                let same: Vec<usize> = pool.iter().copied().filter(|&m| sheet.anims[m].pose == pose).collect();
                if !same.is_empty() {
                    pool = same;
                }
            }
            let idx = *self.chosen.entry((g, dir)).or_insert_with(|| pool[rng.gen_range(0..pool.len())]);
            let a = &sheet.anims[idx];
            return Pick { anim: idx, mirror: a.facing != 0 && a.facing != dir, fallback: i > 0 };
        }
        Pick { anim: 0, mirror: false, fallback: true }
    }
}

pub(crate) unsafe extern "system" fn wndproc(hwnd: HWND, msg: u32, wp: WPARAM, lp: LPARAM) -> LRESULT {
    if msg == WM_MOUSEACTIVATE {
        return LRESULT(MA_NOACTIVATE as isize);
    }
    DefWindowProcW(hwnd, msg, wp, lp)
}

pub struct Overlay {
    pub hwnd: isize,
    mem: HDC,
    bmp: HBITMAP,
    old: HGDIOBJ,
    bits: *mut u8,
    size: (i32, i32),
    drawn: Option<(usize, u32, bool, i32, (i32, i32))>,
    pos: (i32, i32),
    playing: (usize, bool),
    started: Instant,
    /// Scaled cells for the current on-screen size.
    cells: HashMap<(u32, u32), Vec<u8>>,
    cell_size: (i32, i32),
    /// Sheet column drawn last (the bed cuts its front rim around her paw in exactly this frame).
    pub frame: u32,
    /// Set by the brain for distance-driven cycles (walk with steps): index into seq instead of the clock.
    pub force: Option<usize>,
    /// Bumped whenever the window buffer is redrawn (her petting halo rebuilds its mask on change).
    pub gen: u64,
}

impl Overlay {
    pub fn new() -> Overlay {
        unsafe {
            let inst = GetModuleHandleW(None).expect("module handle");
            let class = w!("HenryPetOverlay");
            let wc = WNDCLASSW { lpfnWndProc: Some(wndproc), hInstance: inst.into(), lpszClassName: class, ..Default::default() };
            RegisterClassW(&wc);
            let hwnd = CreateWindowExW(
                WS_EX_LAYERED | WS_EX_TRANSPARENT | WS_EX_TOPMOST | WS_EX_TOOLWINDOW | WS_EX_NOACTIVATE,
                class,
                w!("Henry"),
                WS_POPUP,
                0,
                0,
                1,
                1,
                None,
                None,
                Some(inst.into()),
                None,
            )
            .expect("overlay window");
            let screen = GetDC(None);
            let mem = CreateCompatibleDC(Some(screen));
            ReleaseDC(None, screen);
            Overlay {
                hwnd: hwnd.0 as isize,
                mem,
                bmp: HBITMAP::default(),
                old: HGDIOBJ::default(),
                bits: std::ptr::null_mut(),
                size: (0, 0),
                drawn: None,
                pos: (i32::MIN, i32::MIN),
                playing: (usize::MAX, false),
                started: Instant::now(),
                cells: HashMap::new(),
                cell_size: (0, 0),
                frame: 0,
                force: None,
                gen: 0,
            }
        }
    }

    /// What is on screen now: window buffer (premultiplied BGRA), its screen position and size, generation.
    pub fn buffer(&self) -> Option<(&[u8], (i32, i32), (i32, i32), u64)> {
        if self.bits.is_null() || self.size.0 <= 0 || self.size.1 <= 0 {
            return None;
        }
        let px = unsafe { std::slice::from_raw_parts(self.bits, (self.size.0 * self.size.1 * 4) as usize) };
        Some((px, self.pos, self.size, self.gen))
    }

    /// Forget scaled cells and what was drawn (the sheet changed: skin switch).
    pub fn invalidate(&mut self) {
        self.cells.clear();
        self.drawn = None;
        self.playing = (usize::MAX, false);
    }

    /// Handle this thread's window messages (call every frame).
    pub fn pump(&self) {
        unsafe {
            let mut msg = MSG::default();
            while PeekMessageW(&mut msg, None, 0, 0, PM_REMOVE).as_bool() {
                let _ = TranslateMessage(&msg);
                DispatchMessageW(&msg);
            }
        }
    }

    fn resize(&mut self, w: i32, h: i32) {
        unsafe {
            if !self.bmp.is_invalid() {
                SelectObject(self.mem, self.old);
                let _ = DeleteObject(self.bmp.into());
            }
            let bi = BITMAPINFO {
                bmiHeader: BITMAPINFOHEADER {
                    biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
                    biWidth: w,
                    biHeight: -h,
                    biPlanes: 1,
                    biBitCount: 32,
                    biCompression: BI_RGB.0,
                    ..Default::default()
                },
                ..Default::default()
            };
            let mut bits: *mut core::ffi::c_void = std::ptr::null_mut();
            self.bmp = CreateDIBSection(Some(self.mem), &bi, DIB_RGB_COLORS, &mut bits, None, 0).expect("dib");
            self.old = SelectObject(self.mem, self.bmp.into());
            self.bits = bits as *mut u8;
            self.size = (w, h);
            self.drawn = None;
        }
    }

    /// Draw animation `pick` (cycle `ms`; `still` = hold its first frame) scaled to w x h, rotated ±90°
    /// if asked (window becomes h x w), at screen (x, y).
    #[allow(clippy::too_many_arguments)]
    pub fn render(&mut self, now: Instant, sheet: &Sheet, pick: Pick, ms: u32, still: bool, rotate: i32, x: i32, y: i32, w: i32, h: i32) {
        if (pick.anim, pick.mirror) != self.playing {
            self.playing = (pick.anim, pick.mirror);
            self.started = now;
        }
        let a = &sheet.anims[pick.anim.min(sheet.anims.len() - 1)];
        let n = a.seq.len().max(1);
        let step = (now.saturating_duration_since(self.started).as_millis() as u64 * n as u64 / ms.max(1) as u64) as usize;
        let i = match self.force {
            _ if still => 0,
            Some(f) => f.min(n - 1),
            _ if a.once => step.min(n - 1),
            _ => step % n,
        };
        let frame = a.seq.get(i).copied().unwrap_or(0);
        self.frame = frame;
        let (ww, wh) = if rotate != 0 { (h, w) } else { (w, h) };
        if self.size != (ww, wh) {
            self.resize(ww, wh);
        }
        if self.cell_size != (w, h) {
            self.cells.clear();
            self.cell_size = (w, h);
        }
        let key = (pick.anim, frame, pick.mirror, rotate, (w, h));
        let dirty = self.drawn != Some(key);
        if dirty {
            let row = a.row;
            let cell = self.cells.entry((row, frame)).or_insert_with(|| sheet.scaled_cell(row, frame, w as u32, h as u32));
            let out = unsafe { std::slice::from_raw_parts_mut(self.bits, (ww * wh * 4) as usize) };
            blit(out, cell, ww, wh, w, h, pick.mirror, rotate);
            self.drawn = Some(key);
            self.gen += 1;
        }
        if dirty || self.pos != (x, y) {
            self.pos = (x, y);
            unsafe {
                let blend = BLENDFUNCTION { BlendOp: AC_SRC_OVER as u8, BlendFlags: 0, SourceConstantAlpha: 255, AlphaFormat: AC_SRC_ALPHA as u8 };
                let _ = UpdateLayeredWindow(
                    HWND(self.hwnd as *mut _),
                    None,
                    Some(&POINT { x, y }),
                    Some(&SIZE { cx: ww, cy: wh }),
                    Some(self.mem),
                    Some(&POINT { x: 0, y: 0 }),
                    COLORREF(0),
                    Some(&blend),
                    ULW_ALPHA,
                );
            }
        }
    }
}

impl Overlay {
    /// Draw `pick` bent along the held chain (slinky.rs): strips of 3 art rows, each turned along the
    /// body line's tangent and stretched to its arc length, nearest sampling at screen resolution (hard
    /// pixels, top-down so the one-row overlap hides seams). Window = square around the scruff that fits
    /// any pose. Returns the window rect.
    #[allow(clippy::too_many_arguments)]
    pub fn render_slinky(&mut self, now: Instant, sheet: &Sheet, pick: Pick, ms: u32, body: &crate::slinky::Slinky, w: i32, h: i32) -> (i32, i32, i32, i32) {
        if (pick.anim, pick.mirror) != self.playing {
            self.playing = (pick.anim, pick.mirror);
            self.started = now;
        }
        let a = &sheet.anims[pick.anim.min(sheet.anims.len() - 1)];
        let n = a.seq.len().max(1);
        let step = (now.saturating_duration_since(self.started).as_millis() as u64 * n as u64 / ms.max(1) as u64) as usize;
        let i = if a.once { step.min(n - 1) } else { step % n };
        let frame = a.seq.get(i).copied().unwrap_or(0);
        let k = w as f64 / sheet.cell_w as f64;
        let (pvx, pvy) = (body.pivot.0 * k, body.pivot.1 * k);
        let reach = [(0.0, 0.0), (w as f64, 0.0), (0.0, h as f64), (w as f64, h as f64)]
            .iter()
            .map(|(x, y)| ((x - pvx).powi(2) + (y - pvy).powi(2)).sqrt())
            .fold(0.0, f64::max);
        let s = (reach * 2.0).ceil() as i32 + 4;
        if self.size != (s, s) {
            self.resize(s, s);
        }
        if self.cell_size != (w, h) {
            self.cells.clear();
            self.cell_size = (w, h);
        }
        let (sx0, sy0) = body.scruff();
        let (x, y) = ((sx0 - s as f64 / 2.0).round() as i32, (sy0 - s as f64 / 2.0).round() as i32);
        let row = a.row;
        let cell = self.cells.entry((row, frame)).or_insert_with(|| sheet.scaled_cell(row, frame, w as u32, h as u32));
        let out = unsafe { std::slice::from_raw_parts_mut(self.bits, (s * s * 4) as usize) };
        slinky_into(out, s, (x, y), cell, w, h, sheet.cell_h as f64, k, pick.mirror, body);
        self.drawn = None;
        self.gen += 1;
        self.pos = (x, y);
        unsafe {
            let blend = BLENDFUNCTION { BlendOp: AC_SRC_OVER as u8, BlendFlags: 0, SourceConstantAlpha: 255, AlphaFormat: AC_SRC_ALPHA as u8 };
            let _ = UpdateLayeredWindow(
                HWND(self.hwnd as *mut _),
                None,
                Some(&POINT { x, y }),
                Some(&SIZE { cx: s, cy: s }),
                Some(self.mem),
                Some(&POINT { x: 0, y: 0 }),
                COLORREF(0),
                Some(&blend),
                ULW_ALPHA,
            );
        }
        (x, y, s, s)
    }
}

/// Draw a scaled cell (premultiplied BGRA, w x h screen px; `cell_h` = its height in art px, `k` = scale)
/// bent along a soft chain (slinky.rs) into the s x s window buffer whose top-left is screen `origin`:
/// strips of 3 art rows, each turned along the body line's tangent and stretched to its arc length,
/// nearest sampling at screen resolution (hard pixels, top-down so the one-row overlap hides seams).
/// Shared by Henry (held by the scruff) and her bed (held by one end).
#[allow(clippy::too_many_arguments)]
pub fn slinky_into(out: &mut [u8], s: i32, origin: (i32, i32), cell: &[u8], w: i32, h: i32, cell_h: f64, k: f64, mirror: bool, body: &crate::slinky::Slinky) {
    const ROWS: f64 = 3.0;
    let (x, y) = origin;
    let (pvx, pvy) = (body.pivot.0 * k, body.pivot.1 * k);
    out.fill(0);
    let lb = body.bone(); // screen px per bone
    let ch = cell_h;
    let mut r = 0.0;
    while r < ch {
        let rows = ROWS.min(ch - r);
        let (v0, v1) = (r * k, (r + rows + if r + rows < ch { 1.0 } else { 0.0 }) * k);
        // strip centre on the body line (u = bones from the scruff)
        let vc = (r + rows / 2.0) * k;
        let (cx, cy, tx, ty) = body.at((vc - pvy) / lb);
        let sp = (tx * tx + ty * ty).sqrt().max(1e-6);
        let (yx, yy) = (tx / sp, ty / sp); // along the body
        let (xx, xy) = (yy, -yx); // across, art's +x
        let per = sp / lb; // screen px of body line per screen px of art
        // window-local centre and the strip's bounding box
        let (lcx, lcy) = (cx - x as f64, cy - y as f64);
        let (hw, hh) = (w as f64, (v1 - v0) * per + 2.0);
        let ext_x = hw * xx.abs() + hh * yx.abs();
        let ext_y = hw * xy.abs() + hh * yy.abs();
        let (bx0, bx1) = (((lcx - ext_x).floor() as i32).max(0), ((lcx + ext_x).ceil() as i32).min(s - 1));
        let (by0, by1) = (((lcy - ext_y).floor() as i32).max(0), ((lcy + ext_y).ceil() as i32).min(s - 1));
        for dy in by0..=by1 {
            for dx in bx0..=bx1 {
                let (ox, oy) = (dx as f64 + 0.5 - lcx, dy as f64 + 0.5 - lcy);
                let lx = ox * xx + oy * xy;
                let ly = (ox * yx + oy * yy) / per;
                let v = vc + ly;
                if v < v0 || v >= v1 {
                    continue;
                }
                let (u, v) = ((pvx + lx).floor() as i32, v.floor() as i32);
                if u < 0 || v < 0 || u >= w || v >= h {
                    continue;
                }
                let u = if mirror { w - 1 - u } else { u };
                let si = ((v * w + u) * 4) as usize;
                if cell[si + 3] == 0 {
                    continue;
                }
                let o = ((dy * s + dx) * 4) as usize;
                out[o..o + 4].copy_from_slice(&cell[si..si + 4]);
            }
        }
        r += rows;
    }
}

/// Copy a w x h cell into the ww x wh window buffer, mirrored and/or rotated ±90°.
#[allow(clippy::too_many_arguments)]
fn blit(out: &mut [u8], cell: &[u8], ww: i32, wh: i32, w: i32, h: i32, mirror: bool, rotate: i32) {
    for dy in 0..wh {
        for dx in 0..ww {
            // (u, v) in the unrotated w x h picture
            let (u, v) = match rotate {
                0 => (dx, dy),
                r if r > 0 => (dy, h - 1 - dx),
                _ => (w - 1 - dy, dx),
            };
            let u = if mirror { w - 1 - u } else { u };
            let i = ((dy * ww + dx) * 4) as usize;
            if u < 0 || v < 0 || u >= w || v >= h {
                out[i..i + 4].copy_from_slice(&[0, 0, 0, 0]);
                continue;
            }
            let s = ((v * w + u) * 4) as usize;
            out[i..i + 4].copy_from_slice(&cell[s..s + 4]);
        }
    }
}
